@dataclass
class GtfsFeed:
    """The row lists of one GTFS feed, plus :meth:`write` and small helpers."""

    agency: List[AgencyRow]
    routes: List[RouteRow]
    stops: List[StopRow]
    trips: List[TripRow]
    stop_times: List[StopTimeRow]
    shapes: List[ShapeRow]
    calendar: List[CalendarRow]
    feed_info: List[FeedInfoRow]
    feed_start: date
    feed_end: date
    stats: BuildStats = field(default_factory=BuildStats)

    def stop_times_by_trip(self) -> List[List[StopTimeRow]]:
        """Return one stop-time list per trip, ordered by ``stop_sequence``."""
        grouped: Dict[str, List[StopTimeRow]] = {}
        for row in self.stop_times:
            grouped.setdefault(row.trip_id, []).append(row)
        return [
            sorted(rows, key=lambda row: row.stop_sequence)
            for rows in grouped.values()
        ]

    def write(
        self, path: Path, *, extra_tables: Optional[Mapping[str, str]] = None
    ) -> None:
        """Write the feed as a zip containing the required tables.

        Args:
            path: destination zip path (its parent is created).
            extra_tables: optional ``{filename: csv_text}`` tables to append,
                e.g. the Task 8 ``fare_attributes.txt`` / ``fare_rules.txt``
                rendered by :func:`pipeline.fares.build_gtfs_fare_tables`. Names
                must be plain ``.txt`` filenames and must not overwrite a
                generated table or ``LICENSE-DATA.txt``.

        The zip is deterministic (fixed entry timestamps, sorted tables), so the
        same feed always hashes to the same bytes for the Task 8 manifest. Text
        files are UTF-8 with BOM. The ODbL notice is always written last and
        always present.
        """
        destination = Path(path)
        destination.parent.mkdir(parents=True, exist_ok=True)

        tables: List[Tuple[str, Type[Any], Sequence[Any]]] = [
            ("agency.txt", AgencyRow, self.agency),
            ("routes.txt", RouteRow, self.routes),
            ("stops.txt", StopRow, self.stops),
            ("trips.txt", TripRow, self.trips),
            ("stop_times.txt", StopTimeRow, self.stop_times),
            ("shapes.txt", ShapeRow, self.shapes),
            ("calendar.txt", CalendarRow, self.calendar),
            ("feed_info.txt", FeedInfoRow, self.feed_info),
        ]
        generated_names = {filename for filename, _, _ in tables} | {"LICENSE-DATA.txt"}
        extra: List[Tuple[str, str]] = []
        for filename in sorted(extra_tables or {}):
            _validate_extra_table_name(filename, generated_names)
            extra.append((filename, extra_tables[filename]))

        with zipfile.ZipFile(destination, "w", compression=zipfile.ZIP_DEFLATED) as archive:
            for filename, row_type, rows in tables:
                archive.writestr(_zip_info(filename), _csv_bytes(row_type, rows))
            for filename, text in extra:
                archive.writestr(_zip_info(filename), text.encode("utf-8-sig"))
            archive.writestr(
                _zip_info("LICENSE-DATA.txt"), LICENCE_TEXT.encode("utf-8-sig")
            )


def generate_trips(
    headway_peak_min: int, headway_offpeak_min: int
) -> List[TripSpec]:
    """Generate departures for both directions over the 05:00-22:00 service day.

    The formula is ``ceil(window_minutes / headway)`` departures per window per
    direction, implemented as ``range(start, end, headway)``. It returns
    direction 0 then direction 1, each sorted by departure time. With 4/9 min
    headways this yields 328 trips (see the module docstring for the full
    arithmetic).

    Raises:
        ValueError: if either headway is not a positive integer number of minutes.
    """
    for name, value in (
        ("headway_peak_min", headway_peak_min),
        ("headway_offpeak_min", headway_offpeak_min),
    ):
        if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
            raise ValueError(
                f"{name} must be a positive integer number of minutes, got {value!r}"
            )

    trips: List[TripSpec] = []
    for direction_id in (0, 1):
        departures: set[int] = set()
        for start, end in PEAK_WINDOWS:
            departures.update(range(start, end, headway_peak_min))
        for start, end in OFFPEAK_WINDOWS:
            departures.update(range(start, end, headway_offpeak_min))
        for minute in sorted(departures):
            trips.append(TripSpec(direction_id, _format_minutes(minute), minute))
    return trips


def build_feed(
    routes: Sequence[RouteDef],
    agency: AgencyInfo,
    feed_start: date,
    feed_end: date,
) -> GtfsFeed:
    """Build the GTFS core from route definitions.

    Args:
        routes: route definitions; :class:`pipeline.osm_routes.RouteRelation`
            instances are accepted directly because they subclass
            :class:`RouteDef`.
        agency: publisher metadata for ``agency.txt`` and ``feed_info.txt``.
        feed_start: first service date (inclusive).
        feed_end: last service date (inclusive).

    Routes with no resolvable geometry or fewer than two usable stops are
    skipped and counted in :attr:`GtfsFeed.stats`; they never abort the build.
    Route ids must be unique: a later duplicate is skipped and counted.

    Raises:
        ValueError: if the feed date range is inverted, no routes are supplied,
            a route_type is unsupported, or a route carries a non-positive
            headway.
    """
    if not isinstance(feed_start, date) or not isinstance(feed_end, date):
        raise ValueError("feed_start and feed_end must be datetime.date values")
    if feed_start > feed_end:
        raise ValueError(
            f"feed_start {feed_start.isoformat()} is after feed_end {feed_end.isoformat()}"
        )
    if not routes:
        raise ValueError("build_feed needs at least one route definition")

    counters = {
        "routes_in": len(routes),
        "routes_written": 0,
        "routes_skipped_no_geometry": 0,
        "routes_skipped_too_few_stops": 0,
        "routes_skipped_duplicate_id": 0,
        "dangling_members": 0,
    }
    route_rows: List[RouteRow] = []
    stop_rows: List[StopRow] = []
    trip_rows: List[TripRow] = []
    stop_time_rows: List[StopTimeRow] = []
    shape_rows: List[ShapeRow] = []
    accepted_route_ids: set[str] = set()
    seen_stop_ids: set[str] = set()

    for route in routes:
        counters["dangling_members"] += int(getattr(route, "skipped_members", 0))

        if route.route_type not in SUPPORTED_ROUTE_TYPES:
            raise ValueError(
                f"route {route.route_id!r} has unsupported route_type "
                f"{route.route_type!r}; supported: {sorted(SUPPORTED_ROUTE_TYPES)}"
            )
        if route.route_id in accepted_route_ids:
            counters["routes_skipped_duplicate_id"] += 1
            continue

        shape = _clean_shape(route.shape)
        if len(shape) < 2:
            counters["routes_skipped_no_geometry"] += 1
            continue

        stops = _clean_stops(route, shape)
        if len(stops) < 2:
            counters["routes_skipped_too_few_stops"] += 1
            continue

        accepted_route_ids.add(route.route_id)
        counters["routes_written"] += 1

        short_name = route.short_name.strip() or route.name.strip() or route.route_id
        long_name = route.name.strip() or short_name
        route_rows.append(
            RouteRow(
                route_id=route.route_id,
                agency_id=agency.agency_id,
                route_short_name=short_name,
                route_long_name=long_name,
                route_type=route.route_type,
            )
        )

        for stop in stops:
            if stop.stop_id in seen_stop_ids:
                continue
            seen_stop_ids.add(stop.stop_id)
            stop_rows.append(
                StopRow(
                    stop_id=stop.stop_id,
                    stop_name=stop.name,
                    stop_lat=round(stop.lat, 6),
                    stop_lon=round(stop.lon, 6),
                )
            )

        shape_id = f"{route.route_id}:shape"
        for sequence, (lat, lon) in enumerate(shape, start=1):
            shape_rows.append(ShapeRow(shape_id, lat, lon, sequence))

        segment_minutes = SEGMENT_MINUTES[route.route_type]
        specs = generate_trips(route.headway_peak_min, route.headway_offpeak_min)
        per_direction_counts = {0: 0, 1: 0}
        for spec in specs:
            per_direction_counts[spec.direction_id] += 1
            trip_id = (
                f"{route.route_id}:d{spec.direction_id}:"
                f"{per_direction_counts[spec.direction_id]:03d}"
            )
            trip_rows.append(
                TripRow(
                    route_id=route.route_id,
                    service_id=SERVICE_ID,
                    trip_id=trip_id,
                    direction_id=spec.direction_id,
                    shape_id=shape_id,
                )
            )

            ordered_stops = stops if spec.direction_id == 0 else tuple(reversed(stops))
            minute = spec.departure_minutes
            for sequence, stop in enumerate(ordered_stops, start=1):
                if sequence > 1:
                    minute += segment_minutes
                timestamp = _format_minutes(minute)
                stop_time_rows.append(
                    StopTimeRow(
                        trip_id=trip_id,
                        arrival_time=timestamp,
                        departure_time=timestamp,
                        stop_id=stop.stop_id,
                        stop_sequence=sequence,
                    )
                )

    calendar_row = CalendarRow(
        service_id=SERVICE_ID,
        monday=1,
        tuesday=1,
        wednesday=1,
        thursday=1,
        friday=1,
        saturday=1,
        sunday=1,
        start_date=_gtfs_date(feed_start),
        end_date=_gtfs_date(feed_end),
    )
    feed_info_row = FeedInfoRow(
        feed_publisher_name=agency.name,
        feed_publisher_url=agency.url,
        feed_lang=agency.lang,
        feed_start_date=_gtfs_date(feed_start),
        feed_end_date=_gtfs_date(feed_end),
        feed_version="biyahey-v1",
    )
    agency_row = AgencyRow(
        agency_id=agency.agency_id,
        agency_name=agency.name,
        agency_url=agency.url,
        agency_timezone=agency.timezone,
        agency_lang=agency.lang,
    )

    return GtfsFeed(
        agency=[agency_row],
        routes=route_rows,
        stops=stop_rows,
        trips=trip_rows,
        stop_times=stop_time_rows,
        shapes=shape_rows,
        calendar=[calendar_row],
        feed_info=[feed_info_row],
        feed_start=feed_start,
        feed_end=feed_end,
        stats=BuildStats(**counters),
    )


