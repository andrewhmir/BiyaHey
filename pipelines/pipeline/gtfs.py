#: Exact attribution string required by spec Appendix A / the licence gate.
ODBL_ATTRIBUTION = (
    "© OpenStreetMap contributors — data available under the Open Database "
    "License (ODbL) 1.0"
)

#: Exact CC BY-SA 2.0 attribution required when a published feed carries route
#: inventory transcribed from the OSM Wiki (spec Appendix A; ruling R32).
WIKI_INVENTORY_ATTRIBUTION = (
    "Route inventory derived from OpenStreetMap Wiki (CC BY-SA 2.0)"
)

#: Last line of ``LICENSE-DATA.txt``; extra attribution sections are inserted
#: immediately above it, so the ODbL notice itself never changes.
LICENCE_FOOTER = "Feed generated by BiyaHey! (https://biyahey.example)."

#: Base contents of ``LICENSE-DATA.txt`` inside every generated feed (before any
#: optional attribution section added by :func:`licence_text`).
LICENCE_TEXT = f"""BiyaHey! generated GTFS feed - data licence
==========================================

This feed is a derived database of OpenStreetMap data and is published under
the Open Database License (ODbL) 1.0.

{ODBL_ATTRIBUTION}

ODbL 1.0: https://opendatacommons.org/licenses/odbl/1-0/

You are free to copy, distribute, transmit and adapt this database, provided
that you attribute OpenStreetMap contributors, distribute any adapted database
under the same ODbL 1.0 licence, and keep this notice with the data.

Route geometry and stop locations come from OpenStreetMap route relations.
Stop times and trip schedules are synthesized from configured headways for
routing purposes; they are not observed vehicle movements.

{LICENCE_FOOTER}
"""


def licence_text(wiki_inventory_attribution: Optional[str] = None) -> str:
    """Return ``LICENSE-DATA.txt`` contents, optionally with the CC BY-SA notice.

    Args:
        wiki_inventory_attribution: when the feed contains routes transcribed
            from the CC BY-SA 2.0 OSM Wiki inventory, pass
            :data:`WIKI_INVENTORY_ATTRIBUTION`. A "Route inventory attribution"
            section carrying that exact string is inserted above the feed
            footer (spec 8.2; ruling R32). ``None`` (the GTFS-core default)
            returns :data:`LICENCE_TEXT` unchanged, so a feed built only from
            OSM never claims a wiki derivation.

    The ODbL notice and the spec Appendix A attribution are identical in both
    cases: R32 adds a section, it does not rewrite the existing notice.
    """
    attribution = str(wiki_inventory_attribution or "").strip()
    if not attribution:
        return LICENCE_TEXT
    section = "\n".join(
        (
            "Route inventory attribution",
            "---------------------------",
            "",
            "This feed also contains route inventory transcribed from the",
            'OpenStreetMap Wiki "Metro Manila/Jeepney and UV Express routes"',
            "page, which is published under CC BY-SA 2.0:",
            "",
            attribution,
            "",
            "CC BY-SA 2.0: https://creativecommons.org/licenses/by-sa/2.0/",
            "",
        )
    )
    prefix, footer, suffix = LICENCE_TEXT.rpartition(LICENCE_FOOTER)
    if not footer:  # defensive: the notice is never dropped
        return LICENCE_TEXT + "\n" + section
    return f"{prefix}{section}\n{footer}{suffix}"


def read_licence_text(path: Path) -> str:
    """Read the licence/attribution text stored inside a generated feed zip.

    Args:
        path: a generated ``gtfs.zip``.

    Returns:
        The decoded ``LICENSE-DATA.txt`` text, plus ``attributions.txt`` when a
        feed carries one, joined by a newline. The licence gate uses this to
        check the *artifact*, not just the manifest (ruling R32).

    Raises:
        FileNotFoundError: the zip does not exist.
        ValueError: the file is not a readable zip, or the feed contains no
            licence/attribution table.
    """
    archive_path = Path(path)
    try:
        with zipfile.ZipFile(archive_path) as archive:
            names = set(archive.namelist())
            texts = [
                archive.read(name).decode("utf-8-sig")
                for name in ("LICENSE-DATA.txt", "attributions.txt")
                if name in names
            ]
    except zipfile.BadZipFile as exc:
        raise ValueError(f"{archive_path}: not a valid feed zip: {exc}") from exc
    if not texts:
        raise ValueError(
            f"{archive_path}: feed has no licence/attribution table "
            "(expected LICENSE-DATA.txt)"
        )
    return "\n".join(texts)


#: Default headways in minutes. The brief pins the service day but not the
#: headways; 4/9 make the arithmetic above explicit and are overridable per
#: :class:`RouteDef` (the curated inventory supplies its own values in Task 7).
DEFAULT_HEADWAY_PEAK_MIN = 4
DEFAULT_HEADWAY_OFFPEAK_MIN = 9

#: Service day boundaries in minutes since midnight (end exclusive).
SERVICE_START_MIN = 5 * 60
SERVICE_END_MIN = 22 * 60

#: Peak windows (start inclusive, end exclusive) in minutes since midnight.
PEAK_WINDOWS: Tuple[Tuple[int, int], ...] = ((6 * 60, 9 * 60), (16 * 60, 19 * 60))

#: Off-peak windows (start inclusive, end exclusive) in minutes since midnight.
OFFPEAK_WINDOWS: Tuple[Tuple[int, int], ...] = (
    (5 * 60, 6 * 60),
    (9 * 60, 16 * 60),
    (19 * 60, 22 * 60),
)

#: Indicative minutes between consecutive stops, by GTFS route_type. This is a
#: schedule placeholder, not a measured run time; it only has to be monotonic.
SEGMENT_MINUTES: Dict[int, int] = {1: 3, 3: 2, 4: 5}

#: Route types this builder can emit (pinned mode mapping, Task 6).
SUPPORTED_ROUTE_TYPES = frozenset(SEGMENT_MINUTES)

#: GTFS calendar service id shared by every generated trip.
SERVICE_ID = "daily"


@dataclass(frozen=True)
class StopRef:
    """A stop or platform used by one route.

    ``stop_id`` is namespaced by the route id (``<route_id>:node:<osm id>``,
    ``<route_id>:way:<osm id>`` or ``<route_id>:landmark:<n>``) so that a stop
    never collides across routes and ids are stable between builds.
    """

    stop_id: str
    name: str
    lat: float
    lon: float


@dataclass(frozen=True)
class RouteDef:
    """One GTFS route, ready for :func:`build_feed`.

    ``stops`` are in travel order for direction 0; direction 1 is the reverse.
    ``shape`` is ``((lat, lon), ...)`` in travel order. ``distance_km`` is
    carried for downstream fare/provenance work (Task 7) and is not consumed
    here.
    """

    route_id: str
    route_type: int
    name: str
    short_name: str = ""
    stops: Tuple[StopRef, ...] = ()
    shape: Tuple[Point, ...] = ()
    distance_km: Optional[float] = None
    headway_peak_min: int = DEFAULT_HEADWAY_PEAK_MIN
    headway_offpeak_min: int = DEFAULT_HEADWAY_OFFPEAK_MIN


