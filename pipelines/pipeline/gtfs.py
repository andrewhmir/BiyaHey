"""GTFS core builder: OSM route definitions in, a minimal valid GTFS zip out.

Scope (Task 6 of the data spine)
--------------------------------
This module owns the *GTFS core* only: agency, routes, stops, trips, stop
times, shapes, calendar and feed info, plus the mandatory ODbL notice. Fares
(Task 8), the provenance manifest (Task 8) and the OSM reader (``osm_routes``)
are separate modules: the core build stays fare-free, and the publish stage
attaches the rendered ``fare_*`` tables through
:meth:`GtfsFeed.write(extra_tables=...)` and, because its merged feed carries
routes transcribed from the CC BY-SA 2.0 OSM Wiki inventory, the inventory
attribution through
:meth:`GtfsFeed.write(wiki_inventory_attribution=...)` (ruling R32).

Trip generation — the pinned arithmetic (ruling R8)
---------------------------------------------------
The service day is 05:00-22:00. Peak periods are 06:00-09:00 and 16:00-19:00;
everything else inside the service day is off-peak. Trips are generated for
**both directions**. For each window the number of departures is::

    ceil(window_minutes / headway)

implemented as ``range(window_start, window_end, headway)`` (a departure exactly
at the window end belongs to the next window). With the default headways used
by the tests and by :class:`RouteDef` (4 min peak, 9 min off-peak)::

    peak:    06:00-09:00  180 / 4 = 45
             16:00-19:00  180 / 4 = 45            -> 90 per direction
    offpeak: 05:00-06:00   60 / 9 =  6.67 ->  7
             09:00-16:00  420 / 9 = 46.67 -> 47
             19:00-22:00  180 / 9 = 20              -> 74 per direction
    90 + 74 = 164 trips per direction
    164 x 2 directions = 328 trips

The plan's ``272`` was a placeholder; ``328`` is the number this formula
produces and the number pinned by ``tests/test_gtfs.py``. The per-window
``ceil`` and the combined-period ``ceil`` happen to agree here; the
per-window form is the one implemented and documented.

Other deliberate decisions
--------------------------
* Stop times are *indicative*: each hop costs a constant number of minutes per
  mode (:data:`SEGMENT_MINUTES`), so times are strictly non-decreasing within a
  trip. v1 has no observed vehicle movements and does not pretend to.
* A route whose shape has fewer than two resolvable points is skipped and
  counted (``BuildStats.routes_skipped_no_geometry``); a route with fewer than
  two stops after cleaning is skipped and counted too.
* Shapes are emitted **per travel direction**: ``<route_id>:shape:0`` is the
  RouteDef shape and ``<route_id>:shape:1`` is the same points reversed, and a
  trip references the shape of its own direction. GTFS shapes are ordered in
  travel order, so one shape shared by both directions puts the reverse trip's
  stop order against its shape order; MOTIS then cannot map the stops onto the
  shape and draws the whole trip shape for the leg - the multi-kilometre beeline
  defect that survived route-relation stitching. The cost is roughly twice the
  ``shapes.txt`` rows.
* Rows are plain frozen dataclasses, written with ``csv.writer`` as UTF-8 with
  BOM (``utf-8-sig``). Zip entries use a fixed timestamp, so rebuilding the
  same feed produces byte-identical output — Task 8 hashes it.
"""

