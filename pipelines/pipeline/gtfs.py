def _format_minutes(minutes: int) -> str:
    """Render minutes since midnight as ``HH:MM:SS`` (hours may exceed 23)."""
    hours, remainder = divmod(minutes, 60)
    return f"{hours:02d}:{remainder:02d}:00"


def _gtfs_date(value: date) -> str:
    return value.strftime("%Y%m%d")


def _valid_latlon(lat: float, lon: float) -> bool:
    return (
        isinstance(lat, (int, float))
        and isinstance(lon, (int, float))
        and math.isfinite(lat)
        and math.isfinite(lon)
        and -90.0 <= lat <= 90.0
        and -180.0 <= lon <= 180.0
    )


def _clean_shape(shape: Iterable[Point]) -> Tuple[Point, ...]:
    """Drop invalid points and consecutive duplicates; preserve travel order."""
    cleaned: List[Point] = []
    for lat, lon in shape:
        if not _valid_latlon(lat, lon):
            continue
        point = (float(lat), float(lon))
        if cleaned and cleaned[-1] == point:
            continue
        cleaned.append(point)
    return tuple(cleaned)


def _clean_stops(route: RouteDef, shape: Tuple[Point, ...]) -> Tuple[StopRef, ...]:
    """Return usable stops, synthesizing two landmark stops when none exist."""
    candidates = list(route.stops)
    if not candidates:
        start_name, end_name = _landmark_names(route)
        candidates = [
            StopRef(f"{route.route_id}:landmark:0", start_name, *shape[0]),
            StopRef(f"{route.route_id}:landmark:1", end_name, *shape[-1]),
        ]

    cleaned: List[StopRef] = []
    seen: set[str] = set()
    for stop in candidates:
        if stop.stop_id in seen:
            continue
        if not _valid_latlon(stop.lat, stop.lon):
            continue
        seen.add(stop.stop_id)
        cleaned.append(stop)
    return tuple(cleaned)


def _landmark_names(route: RouteDef) -> Tuple[str, str]:
    """Name synthesized endpoint stops from an ``A - B`` route name."""
    name = route.name.strip()
    for separator in (" – ", " — ", " - ", " to ", "→", "–", "-"):
        if separator in name:
            start, end = name.split(separator, 1)
            start, end = start.strip(), end.strip()
            if start and end:
                return start, end
    if name:
        return f"{name} (start)", f"{name} (end)"
    return f"{route.route_id} start", f"{route.route_id} end"


def _csv_value(value: Any) -> Any:
    if isinstance(value, float):
        return f"{value:.6f}"
    return "" if value is None else value


def _csv_bytes(row_type: Type[Any], rows: Sequence[Any]) -> bytes:
    """Render a table as CSV text (UTF-8 with BOM) with a header row."""
    columns = [column.name for column in fields(row_type)]
    buffer = io.StringIO(newline="")
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(columns)
    for row in rows:
        writer.writerow([_csv_value(getattr(row, column)) for column in columns])
    return buffer.getvalue().encode("utf-8-sig")


def _zip_info(filename: str) -> zipfile.ZipInfo:
    """A reproducible zip entry: fixed timestamp, no host-specific metadata."""
    info = zipfile.ZipInfo(filename=filename, date_time=(1980, 1, 1, 0, 0, 0))
    info.compress_type = zipfile.ZIP_DEFLATED
    return info


def _validate_extra_table_name(filename: str, generated_names: set) -> None:
    """Reject an extra table name that could escape the zip or shadow a table."""
    if (
        not isinstance(filename, str)
        or not filename
        or Path(filename).name != filename
        or not filename.endswith(".txt")
    ):
        raise ValueError(
            f"extra table name must be a plain .txt filename, got {filename!r}"
        )
    if filename in generated_names:
        raise ValueError(
            f"extra table {filename!r} would overwrite a generated table"
        )
