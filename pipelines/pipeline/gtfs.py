#: Default headways in minutes. The brief pins the service day but not the
#: headways; 4/9 make the arithmetic above explicit and are overridable per
#: :class:`RouteDef` (the curated inventory supplies its own values in Task 7).
DEFAULT_HEADWAY_PEAK_MIN = 4
DEFAULT_HEADWAY_OFFPEAK_MIN = 9

#: Service day boundaries in minutes since midnight (end exclusive).
SERVICE_START_MIN = 5 * 60
SERVICE_END_MIN = 22 * 60

#: Peak windows (start inclusive, end exclusive) in minutes since midnight.
PEAK_WINDOWS: Tuple[Tuple[int, int], ...] = ((6 * 60, 9 * 60), (16 * 60, 19 * 60))

#: Off-peak windows (start inclusive, end exclusive) in minutes since midnight.
OFFPEAK_WINDOWS: Tuple[Tuple[int, int], ...] = (
    (5 * 60, 6 * 60),
    (9 * 60, 16 * 60),
    (19 * 60, 22 * 60),
)

#: Indicative minutes between consecutive stops, by GTFS route_type. This is a
#: schedule placeholder, not a measured run time; it only has to be monotonic.
SEGMENT_MINUTES: Dict[int, int] = {1: 3, 3: 2, 4: 5}

#: Route types this builder can emit (pinned mode mapping, Task 6).
SUPPORTED_ROUTE_TYPES = frozenset(SEGMENT_MINUTES)

#: GTFS calendar service id shared by every generated trip.
SERVICE_ID = "daily"


@dataclass(frozen=True)
class StopRef:
    """A stop or platform used by one route.

    ``stop_id`` is namespaced by the route id (``<route_id>:node:<osm id>``,
    ``<route_id>:way:<osm id>`` or ``<route_id>:landmark:<n>``) so that a stop
    never collides across routes and ids are stable between builds.
    """

    stop_id: str
    name: str
    lat: float
    lon: float


@dataclass(frozen=True)
class RouteDef:
    """One GTFS route, ready for :func:`build_feed`.

    ``stops`` are in travel order for direction 0; direction 1 is the reverse.
    ``shape`` is ``((lat, lon), ...)`` in travel order. ``distance_km`` is
    carried for downstream fare/provenance work (Task 7) and is not consumed
    here.
    """

    route_id: str
    route_type: int
    name: str
    short_name: str = ""
    stops: Tuple[StopRef, ...] = ()
    shape: Tuple[Point, ...] = ()
    distance_km: Optional[float] = None
    headway_peak_min: int = DEFAULT_HEADWAY_PEAK_MIN
    headway_offpeak_min: int = DEFAULT_HEADWAY_OFFPEAK_MIN


